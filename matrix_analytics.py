                "volume-heavy Latin America and capital-constrained "
                "East Africa</b><br>"
                f"<span style='font-size:11px; color:{chart_subtext_color};'>"
                "Data source: coffee_adaptation_matrix.csv · "
                "Bubble size ∝ total viable adaptation footprint (ha)"
